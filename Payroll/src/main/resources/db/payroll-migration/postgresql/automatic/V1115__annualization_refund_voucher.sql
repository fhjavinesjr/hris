CREATE TABLE IF NOT EXISTS annualization_refund_voucher (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshotId BIGINT NOT NULL,
    amount NUMERIC(19,2) NOT NULL,
    voucherReference VARCHAR(100) NOT NULL,
    paidDate DATE NOT NULL,
    recordedBy VARCHAR(100) NOT NULL,
    recordedAt TIMESTAMP(6) NOT NULL,
    voidedAt TIMESTAMP(6),
    voidedBy VARCHAR(100),
    voidReason VARCHAR(500),
    CONSTRAINT fk_annual_refund_snapshot FOREIGN KEY (snapshotId) REFERENCES annualization_snapshot(id)
);
CREATE INDEX IF NOT EXISTS idx_annual_refund_snapshot ON annualization_refund_voucher (snapshotId);
