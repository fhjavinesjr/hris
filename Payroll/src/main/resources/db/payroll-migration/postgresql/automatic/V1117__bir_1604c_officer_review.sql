CREATE TABLE IF NOT EXISTS bir_1604c_officer_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    taxYear INTEGER NOT NULL,
    contactNumber VARCHAR(30),
    emailAddress VARCHAR(100),
    sheetsAttached INTEGER,
    refundsReleased VARCHAR(3),
    refundDate DATE,
    overremittanceAmount NUMERIC(19,2),
    firstCreditingMonth INTEGER,
    evidenceReference VARCHAR(255),
    signatoryName VARCHAR(100),
    signatoryTitle VARCHAR(100),
    signatoryTin VARCHAR(30),
    remarks VARCHAR(500),
    basis1601CWithheld NUMERIC(19,2),
    basisAlphalistWithheld NUMERIC(19,2),
    basisPaidRefunds NUMERIC(19,2),
    status VARCHAR(20) NOT NULL,
    updatedBy VARCHAR(100) NOT NULL,
    updatedAt TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_1604c_review_year UNIQUE (taxYear),
    CONSTRAINT ck_1604c_credit_month CHECK (firstCreditingMonth BETWEEN 1 AND 12)
);

CREATE TABLE IF NOT EXISTS bir_1604c_officer_review_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    taxYear INTEGER NOT NULL,
    action VARCHAR(20) NOT NULL,
    previousValues VARCHAR(2000),
    newValues VARCHAR(2000) NOT NULL,
    performedBy VARCHAR(100) NOT NULL,
    performedAt TIMESTAMP(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_1604c_review_audit_year
    ON bir_1604c_officer_review_audit (taxYear, performedAt);
