CREATE TABLE IF NOT EXISTS tax_remittance_1601c (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    taxYear INTEGER NOT NULL,
    taxMonth INTEGER NOT NULL,
    taxesWithheld NUMERIC(19,2) NOT NULL,
    adjustment NUMERIC(19,2) NOT NULL,
    penalties NUMERIC(19,2) NOT NULL,
    amountRemitted NUMERIC(19,2) NOT NULL,
    filingDate DATE,
    remittanceDate DATE,
    remittanceChannel VARCHAR(100),
    referenceNo VARCHAR(100),
    remarks VARCHAR(500),
    evidenceReference VARCHAR(255),
    status VARCHAR(20) NOT NULL,
    recordedBy VARCHAR(100) NOT NULL,
    recordedAt TIMESTAMP(6) NOT NULL,
    updatedBy VARCHAR(100) NOT NULL,
    updatedAt TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_1601c_year_month UNIQUE (taxYear, taxMonth),
    CONSTRAINT ck_1601c_month CHECK (taxMonth BETWEEN 1 AND 12)
);

CREATE TABLE IF NOT EXISTS tax_remittance_1601c_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    taxYear INTEGER NOT NULL,
    taxMonth INTEGER NOT NULL,
    action VARCHAR(20) NOT NULL,
    previousValues VARCHAR(2000),
    newValues VARCHAR(2000) NOT NULL,
    performedBy VARCHAR(100) NOT NULL,
    performedAt TIMESTAMP(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_1601c_audit_period
    ON tax_remittance_1601c_audit (taxYear, taxMonth, performedAt);
