CREATE TABLE IF NOT EXISTS annual_benefit_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "sourceType" VARCHAR(30) NOT NULL,
    "sourceId" BIGINT NOT NULL,
    "employeeNo" VARCHAR(50) NOT NULL,
    "taxYear" INTEGER NOT NULL,
    "sourceAmount" NUMERIC(19,2) NOT NULL,
    "exemptAmount" NUMERIC(19,2) NOT NULL,
    "otherExemptAmount" NUMERIC(19,2) NOT NULL,
    "taxableAmount" NUMERIC(19,2) NOT NULL,
    "exemptBirItem" VARCHAR(4),
    "otherExemptBirItem" VARCHAR(4),
    "taxableBirItem" VARCHAR(4),
    "profileCode" VARCHAR(50) NOT NULL,
    "profileLegalBasis" VARCHAR(200) NOT NULL,
    "profileGuidanceCeiling" NUMERIC(19,2),
    "profileCeilingPeriod" VARCHAR(30),
    reason VARCHAR(500) NOT NULL,
    "reviewedBy" VARCHAR(100) NOT NULL,
    "reviewedAt" TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_annual_benefit_review_source UNIQUE ("sourceType", "sourceId")
);
CREATE INDEX IF NOT EXISTS idx_annual_benefit_review_employee ON annual_benefit_review ("employeeNo", "taxYear");
