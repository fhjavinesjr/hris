package com.payroll.repositories;

import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.regex.Pattern;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

class AnnualizationPersistencePortabilityTest {
    private static final List<String> REPOSITORIES = List.of(
            "AnnualizationSnapshotRepository.java",
            "AnnualizationSnapshotPeriodRepository.java",
            "AnnualizationSnapshotPreviousEmployerRepository.java",
            "AnnualizationSnapshotItemRepository.java",
            "AnnualizationAuditLogRepository.java",
            "AnnualPeraTaxCreditRepository.java",
            "AnnualBenefitReviewRepository.java",
            "AnnualizationRefundVoucherRepository.java",
            "PreviousEmployerTaxDataRepository.java",
            "PayrollDetailRepository.java",
            "PayrollDetailEarningRepository.java",
            "PayrollDetailDeductionRepository.java",
            "PayrollAdjustmentLineRepository.java"
    );

    private static final Pattern PROVIDER_SPECIFIC = Pattern.compile(
            "(?i)nativeQuery\\s*=\\s*true|\\bTOP\\s+\\d+|\\bISNULL\\s*\\(|\\bGETDATE\\s*\\("
                    + "|\\bDATEADD\\s*\\(|\\bCONVERT\\s*\\(|::[a-z_][a-z0-9_]*"
                    + "|\\bILIKE\\b|\\bLIMIT\\s+\\d+|\\bRETURNING\\b");

    @Test
    void annualizationRepositoriesContainNoProviderSpecificQueryConstructs() throws IOException {
        Path repositoryRoot = Path.of("src", "main", "java", "com", "payroll", "repositories");
        for (String filename : REPOSITORIES) {
            String source = Files.readString(repositoryRoot.resolve(filename));
            assertFalse(PROVIDER_SPECIFIC.matcher(source).find(),
                    "Provider-specific query construct found in " + filename);
        }
    }

    @Test
    void alphalistSnapshotMigrationIsPackagedForBothDatabaseProviders() throws IOException {
        Path sqlServer = Path.of("src", "main", "resources", "db", "payroll-migration",
                "sqlserver", "automatic", "V1112__annualization_alphalist_identity.sql");
        Path postgresql = Path.of("src", "main", "resources", "db", "payroll-migration",
                "postgresql", "automatic", "V1112__annualization_alphalist_identity.sql");

        assertTrue(Files.isRegularFile(sqlServer));
        assertTrue(Files.isRegularFile(postgresql));
        assertTrue(Files.readString(sqlServer).contains("COL_LENGTH"));
        assertFalse(Files.readString(sqlServer).contains("ADD COLUMN IF NOT EXISTS"));
        assertTrue(Files.readString(postgresql).contains("ADD COLUMN IF NOT EXISTS"));
        assertFalse(Files.readString(postgresql).contains("COL_LENGTH"));
    }

    @Test
    void annualBenefitReviewMigrationIsPackagedForBothProviders() throws IOException {
        Path root = Path.of("src", "main", "resources", "db", "payroll-migration");
        Path sqlServer = root.resolve(Path.of("sqlserver", "automatic", "V1114__annual_benefit_review.sql"));
        Path postgresql = root.resolve(Path.of("postgresql", "automatic", "V1114__annual_benefit_review.sql"));
        assertTrue(Files.isRegularFile(sqlServer));
        assertTrue(Files.isRegularFile(postgresql));
        assertFalse(Files.readString(sqlServer).contains("GENERATED BY DEFAULT AS IDENTITY"));
        assertFalse(Files.readString(postgresql).contains("IDENTITY(1,1)"));
    }

    @Test
    void refundVoucherMigrationIsPackagedForBothProviders() throws IOException {
        Path root = Path.of("src", "main", "resources", "db", "payroll-migration");
        Path sqlServer = root.resolve(Path.of("sqlserver", "automatic", "V1115__annualization_refund_voucher.sql"));
        Path postgresql = root.resolve(Path.of("postgresql", "automatic", "V1115__annualization_refund_voucher.sql"));
        assertTrue(Files.isRegularFile(sqlServer));
        assertTrue(Files.isRegularFile(postgresql));
        assertTrue(Files.readString(sqlServer).contains("FOREIGN KEY (snapshotId)"));
        assertTrue(Files.readString(postgresql).contains("FOREIGN KEY (snapshotId)"));
        assertFalse(Files.readString(sqlServer).contains("GENERATED BY DEFAULT AS IDENTITY"));
        assertFalse(Files.readString(postgresql).contains("IDENTITY(1,1)"));
    }
}
