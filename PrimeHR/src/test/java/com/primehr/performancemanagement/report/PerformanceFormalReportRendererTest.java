package com.primehr.performancemanagement.report;

import com.primehr.performancemanagement.report.application.PerformanceFormalReportData.*;
import com.primehr.performancemanagement.report.application.PerformanceFormalReportRenderer;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

class PerformanceFormalReportRendererTest {
    private final PerformanceFormalReportRenderer renderer=new PerformanceFormalReportRenderer();
    private static Header header(String title){return new Header(title,"IPCR","FINALIZED","ISOFT TEST AGENCY","Government Center","E-1","Employee One","Administrative Officer V","Human Resource Management","Jan 1, 2026 to Dec 31, 2026","Supervisor | Division Chief","Approver | Director","source-1; "+"a".repeat(64),"b".repeat(64)+"; captured by tester","Generated by tester");}

    @Test void allBeanBackedPerformanceTemplatesProducePdf(){
        byte[] form=renderer.form(new Form(header("INDIVIDUAL PERFORMANCE COMMITMENT AND REVIEW"),new BigDecimal("4.75"),"Outstanding",List.of(new FormRow(1,"Core Functions","Deliver service","100% within period","100 cases","Completed 100 cases","Q: 5 | T: 4",new BigDecimal("100"),new BigDecimal("4.75"),"Verified"))));
        byte[] monitoring=renderer.monitoring(new Monitoring(header("PERFORMANCE MONITORING AND ACCOMPLISHMENT REPORT"),List.of(new MonitoringRow(1,"Jun 30, 2026","Deliver service","Completed 50 cases","50","50%","None","None","On track","ACCEPTED"))));
        byte[] coaching=renderer.coaching(new Coaching(header("PERFORMANCE COACHING RECORD"),"Review delivery","Improve timeliness","Late submissions","Weekly review","Mentoring","Nov 1, 2026","Nov 8, 2026","Progress discussed","Acknowledged",List.of(new ActionRow(1,"Submit weekly tracker","E-1","Nov 1, 2026","IN_PROGRESS","First week submitted","NOT VERIFIED"))));
        byte[] intervention=renderer.intervention(new Intervention(header("INDIVIDUAL DEVELOPMENT PLAN"),"INDIVIDUAL DEVELOPMENT PLAN","DEVELOPMENT_PLAN","Improve service delivery","Coaching and training","E-2","Nov 1, 2026 to Jan 31, 2027","Acknowledged","OPEN LIFECYCLE",List.of(new CheckpointRow(1,"Dec 1, 2026","Complete coaching","PLANNED","",""))));
        assertThat(form).startsWith("%PDF".getBytes()).hasSizeGreaterThan(2_000);
        assertThat(monitoring).startsWith("%PDF".getBytes()).hasSizeGreaterThan(2_000);
        assertThat(coaching).startsWith("%PDF".getBytes()).hasSizeGreaterThan(2_000);
        assertThat(intervention).startsWith("%PDF".getBytes()).hasSizeGreaterThan(2_000);
    }

    @Test void longDynamicPerformanceFormPaginatesWithoutFixedDpcrSlotLimit(){
        List<FormRow> rows=java.util.stream.IntStream.rangeClosed(1,30).mapToObj(i->new FormRow(i,"Dynamic section "+i,"Output "+i,"Indicator "+i,"Target "+i,"Accomplishment "+i,"Q: 5",new BigDecimal("3.3333"),new BigDecimal("4.5"),"Remark "+i)).toList();
        byte[] pdf=renderer.form(new Form(header("DIVISION PERFORMANCE COMMITMENT AND REVIEW"),new BigDecimal("4.5"),"Very Satisfactory",rows));
        assertThat(pdf).startsWith("%PDF".getBytes()).hasSizeGreaterThan(5_000);
    }
}
