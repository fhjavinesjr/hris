package com.primehr.learningdevelopment.report;

import com.primehr.learningdevelopment.report.application.LdFormalReportData.*;
import com.primehr.learningdevelopment.report.application.LdFormalReportRenderer;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

class LdFormalReportRendererTest {
    @Test void beanDrivenTemplateCompilesAndProducesPaginatedPdf() {
        List<Row> rows=java.util.stream.IntStream.rangeClosed(1,35)
                .mapToObj(index->new Row(index,"Development Item","Capability "+index,
                        "Planned intervention and verifiable output "+index,"APPROVED"))
                .toList();
        Document document=new Document(new Header("INDIVIDUAL DEVELOPMENT PLAN","Employee Learning",
                "APPROVED","EMP-00001 | Employee One","Human Resource Management","2026",
                "source-1 | "+"a".repeat(64),"Generated by authorized tester"),rows);

        byte[] pdf=new LdFormalReportRenderer().render(document);

        assertThat(pdf).startsWith("%PDF".getBytes()).hasSizeGreaterThan(5_000);
    }
}
