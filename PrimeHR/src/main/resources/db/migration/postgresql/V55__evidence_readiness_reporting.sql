CREATE TABLE "${primehrSchema}".evidence_readiness_snapshot (
 id VARCHAR(36) PRIMARY KEY,
 agency_id VARCHAR(64) NOT NULL,
 assessment_case_id VARCHAR(36) NOT NULL,
 cycle_id VARCHAR(36) NOT NULL,
 framework_version_id VARCHAR(36) NOT NULL,
 framework_definition_version INTEGER NOT NULL,
 framework_content_revision INTEGER NOT NULL,
 framework_fingerprint VARCHAR(64) NOT NULL,
 case_content_revision INTEGER NOT NULL,
 case_submission_revision INTEGER NOT NULL,
 snapshot_revision INTEGER NOT NULL,
 supersedes_snapshot_id VARCHAR(36),
 total_requirements INTEGER NOT NULL,
 excluded_requirements INTEGER NOT NULL,
 applicable_requirements INTEGER NOT NULL,
 assessed_requirements INTEGER NOT NULL,
 covered_requirements INTEGER NOT NULL,
 completeness_percent NUMERIC(7,2) NOT NULL,
 coverage_percent NUMERIC(7,2) NOT NULL,
 missing_input_count INTEGER NOT NULL,
 expiring_evidence_count INTEGER NOT NULL,
 overdue_action_count INTEGER NOT NULL,
 facts_payload TEXT NOT NULL,
 facts_fingerprint VARCHAR(64) NOT NULL,
 disclaimer VARCHAR(1000) NOT NULL,
 signed_by VARCHAR(100) NOT NULL,
 signed_at TIMESTAMP WITH TIME ZONE NOT NULL,
 sign_off_reason VARCHAR(3000) NOT NULL,
 record_version BIGINT NOT NULL DEFAULT 0,
 created_by VARCHAR(100) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_by VARCHAR(100) NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT fk_evidence_snapshot_case FOREIGN KEY (assessment_case_id) REFERENCES "${primehrSchema}".evidence_assessment_case(id),
 CONSTRAINT fk_evidence_snapshot_cycle FOREIGN KEY (cycle_id) REFERENCES "${primehrSchema}".evidence_assessment_cycle(id),
 CONSTRAINT fk_evidence_snapshot_framework FOREIGN KEY (framework_version_id) REFERENCES "${primehrSchema}".evidence_framework_version(id),
 CONSTRAINT fk_evidence_snapshot_prior FOREIGN KEY (supersedes_snapshot_id) REFERENCES "${primehrSchema}".evidence_readiness_snapshot(id),
 CONSTRAINT uk_evidence_snapshot_revision UNIQUE (agency_id, assessment_case_id, snapshot_revision),
 CONSTRAINT ck_evidence_snapshot_revision CHECK (framework_definition_version >= 1 AND framework_content_revision >= 1 AND case_content_revision >= 0 AND case_submission_revision >= 1 AND snapshot_revision >= 1),
 CONSTRAINT ck_evidence_snapshot_counts CHECK (total_requirements >= 1 AND excluded_requirements >= 0 AND applicable_requirements >= 0 AND assessed_requirements >= 0 AND covered_requirements >= 0 AND missing_input_count >= 0 AND expiring_evidence_count >= 0 AND overdue_action_count >= 0 AND excluded_requirements + applicable_requirements = total_requirements AND assessed_requirements <= total_requirements AND covered_requirements <= applicable_requirements),
 CONSTRAINT ck_evidence_snapshot_percent CHECK (completeness_percent >= 0 AND completeness_percent <= 100 AND coverage_percent >= 0 AND coverage_percent <= 100)
);
CREATE INDEX ix_evidence_snapshot_case ON "${primehrSchema}".evidence_readiness_snapshot(agency_id, assessment_case_id, snapshot_revision);
CREATE INDEX ix_evidence_snapshot_signed ON "${primehrSchema}".evidence_readiness_snapshot(agency_id, signed_at);
