CREATE TABLE [${primehrSchema}].spms_report_metadata_snapshot (
    id VARCHAR(36) PRIMARY KEY,
    agency_id VARCHAR(64) NOT NULL,
    report_kind VARCHAR(30) NOT NULL,
    source_type VARCHAR(30) NOT NULL,
    source_id VARCHAR(36) NOT NULL,
    source_business_revision INT NOT NULL,
    source_record_version BIGINT NOT NULL,
    source_fingerprint VARCHAR(64) NOT NULL,
    template_code VARCHAR(100) NOT NULL,
    template_version INT NOT NULL,
    employee_id BIGINT NOT NULL,
    employee_no VARCHAR(100) NOT NULL,
    employee_name NVARCHAR(300) NOT NULL,
    position_name NVARCHAR(200) NOT NULL,
    plantilla_name NVARCHAR(200),
    area_id BIGINT,
    area_name NVARCHAR(200),
    business_unit_id BIGINT NOT NULL,
    business_unit_name NVARCHAR(200) NOT NULL,
    supervisor_employee_no VARCHAR(100),
    supervisor_name NVARCHAR(300),
    supervisor_position_name NVARCHAR(200),
    approver_employee_no VARCHAR(100),
    approver_name NVARCHAR(300),
    approver_position_name NVARCHAR(200),
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    agency_name NVARCHAR(300) NOT NULL,
    agency_address NVARCHAR(500),
    branding_fingerprint VARCHAR(64) NOT NULL,
    metadata_fingerprint VARCHAR(64) NOT NULL,
    captured_by VARCHAR(100) NOT NULL,
    captured_at DATETIMEOFFSET NOT NULL,
    record_version BIGINT NOT NULL DEFAULT 0,
    created_by VARCHAR(100) NOT NULL,
    created_at DATETIMEOFFSET NOT NULL,
    updated_by VARCHAR(100) NOT NULL,
    updated_at DATETIMEOFFSET NOT NULL,
    CONSTRAINT uk_spms_report_snapshot_source UNIQUE (agency_id, report_kind, source_type, source_id, source_business_revision),
    CONSTRAINT ck_spms_report_snapshot_kind CHECK (report_kind IN ('OPCR','DPCR','IPCR','MONITORING','COACHING','DEVELOPMENT_PLAN','INTERVENTION')),
    CONSTRAINT ck_spms_report_snapshot_source CHECK (source_type IN ('COMMITMENT_VERSION','FINAL_RATING','MONITORING_CASE','COACHING_SESSION','INTERVENTION')),
    CONSTRAINT ck_spms_report_snapshot_revision CHECK (source_business_revision > 0 AND source_record_version >= 0 AND template_version > 0),
    CONSTRAINT ck_spms_report_snapshot_period CHECK (period_end >= period_start)
);

CREATE INDEX ix_spms_report_snapshot_employee ON [${primehrSchema}].spms_report_metadata_snapshot(agency_id, employee_no, period_start);
CREATE INDEX ix_spms_report_snapshot_source ON [${primehrSchema}].spms_report_metadata_snapshot(agency_id, source_type, source_id);
