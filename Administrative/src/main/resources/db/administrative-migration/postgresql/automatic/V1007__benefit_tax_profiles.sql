CREATE TABLE IF NOT EXISTS benefit_tax_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "profileCode" VARCHAR(50) NOT NULL,
    "taxYear" INTEGER NOT NULL,
    label VARCHAR(120) NOT NULL,
    "guidanceCeiling" NUMERIC(19,2),
    "ceilingPeriod" VARCHAR(30),
    "sharedPoolCode" VARCHAR(50),
    "exemptBirItem" VARCHAR(4),
    "taxableBirItem" VARCHAR(4),
    "legalBasis" VARCHAR(200) NOT NULL,
    "sourceUrl" VARCHAR(500),
    CONSTRAINT uq_benefit_tax_profile_year UNIQUE ("profileCode", "taxYear")
);
